// 원본 맵 배열 (4개)
static const int* MAP_DATA[4] = {
    &map0[0][0],
    &map1[0][0],
    &map2[0][0],
    &map3[0][0],
};

// ── Map 클래스 구현 ──────────────────────────────────────────────────────────

Map::Map(int width, int height, int map_index)
    : width(width), height(height), map_index(map_index)
{
    generate();
}

void Map::generate() {
    // 맵 데이터를 2차원 벡터로 복사
    mapData.assign(height, std::vector<int>(width, 0));
    const int* src = MAP_DATA[map_index];
    for (int x = 0; x < height; ++x) {
        for (int y = 0; y < width; ++y) {
            mapData[x][y] = src[x * MAP_W + y];
        }
    }
}

const std::vector<std::vector<int>>& Map::getMapData() const {
    return mapData;
}

std::vector<std::vector<int>>& Map::getMapData() {
    return mapData;
}

// 내부 벽 붕괴: 가장자리(겉 벽)가 아닌 일반 벽(1) 중 랜덤으로 1개만 제거
// 호출될 때마다 내부 벽 1칸씩 사라지는 효과
void Map::collapseInnerWalls() {
    // 내부 벽 위치 목록 수집
    std::vector<std::pair<int,int>> inner_walls;
    for (int x = 1; x < height - 1; ++x) {
        for (int y = 1; y < width - 1; ++y) {
            if (mapData[x][y] == 1) {
                inner_walls.push_back({x, y});
            }
        }
    }

    // 내부 벽이 없으면 아무것도 하지 않음
    if (inner_walls.empty()) return;

    // 랜덤으로 1개 선택해서 제거
    const int idx = std::rand() % static_cast<int>(inner_walls.size());
    mapData[inner_walls[idx].first][inner_walls[idx].second] = 0;
}

// 해당 좌표가 일반 벽(1)인지 확인 (Gate를 놓을 수 있는 벽)
bool Map::isNormalWall(int x, int y) const {
    return (mapData[x][y] == 1);
}
